use strict;
use warnings;
use File::Basename qw(basename);
use File::Copy qw(copy);
use File::Glob qw(:bsd_glob);
use File::Path qw(mkpath);
use File::Spec::Functions qw(catdir splitpath);
use Getopt::Long qw(:config bundling);
use Markdown::Perl;
use grepdocs;

my $prog = basename($0);
# Source files to publish by file extension.
my $fileext_regex = join("|", qw(.md .markdown));


sub usage() {
  print <<EOL
  $prog

  --all                Publish all available files (default).
  --clobber            Publish document even if src is older than dst.
  --filter|-f <regex>  Publish all files whose full PATH match regex.
  --config <file>      Use this config file.
                       Default: '$config_file'.

  --default-config     Print a default config.

  --verbose|-v         Add verbosity to output.
  --version
  --help|-h
EOL
  ;
}


sub main() {
  # Args; No debug output until verbose arg.
  my $opt_print_default_config = 0;
  my $opt_publish_all = 0;
  my $opt_publish_clobber = 0;
  my $opt_filter = "";
  GetOptions (
    'all' => \$opt_publish_all,
    'clobber' => \$opt_publish_clobber,
    'config=s' => \$config_file,
    'default-config' => \$opt_print_default_config,
    'filter|f=s' => \$opt_filter,
    'verbose|v+' => \$opt_verbose,
    'version' => sub { print "$prog $VERSION\n"; exit 0 },
    'help|h|-?' => sub { usage(); exit 0 },
  ) or die "Error with options\n";
  debug(2, "Args");
  debug(2, "Verbose level: $opt_verbose");

  if ($opt_print_default_config) {
    print($default_config->write_string());
    exit 0;
  }

  debug(2, "Start");
  debug(2, "Config");
  my $ini_config = get_config();
  my @sections = get_sections($ini_config);
  debug("Found " . scalar(@sections) . " sections in config");

  debug("Get files");
  foreach my $section (@sections) {
    my @files = ();
    debug("Section $section");
    my $dest_dir = $ini_config->{$section}->{"publish"};
    if (! defined($dest_dir) ) {
      debug("No publish setting found. Nothing to publish. Next");
      next;
    }
    if (! -d $dest_dir || ! -w $dest_dir) {
      die "Cannot write to publish dir $dest_dir";
    }

    my $src_dir = $ini_config->{$section}->{"dir"};
    push(@files, get_files($src_dir, $fileext_regex));
    debug("Found " . scalar(@files) . " files in section $section");

    foreach my $filename (@files) {
      # Construct the html file name and path.
      my $html_dest = $filename;

      # Get the section part of the path.
      $html_dest =~ s/\Q$src_dir\E//;
      debug(3, "html_dest without src_dir: $html_dest");
      my $section_part = (File::Spec->splitpath($html_dest))[1];
      debug(3, "section_part $section_part");
      my $section_dir = catdir($dest_dir, $section_part);
      debug(3, "section_dir: $section_dir");
      if (! -d $section_dir) {
        debug("Make section_dir: $section_dir");
        mkpath($section_dir);
      }

      # Make the html file extension.
      $html_dest =~ s/$fileext_regex/.html/;
      debug(3, "file with html extension: $html_dest");

      # Construct the path.
      my $html_file = catdir($dest_dir, $html_dest);

      # Only publish if src is newer than dst.
      if ( -r $html_file && ! $opt_publish_clobber ) {
        # Get mtime for each file.
        my $src_markdown_mtime = (stat($filename))[9];
        my $dst_html_mtime = (stat($html_file))[9];
        if ($dst_html_mtime > $src_markdown_mtime) {
          my $html_filename = (File::Spec->splitpath($html_dest))[2];
          debug("File " . $section_part . $html_filename . " is newer than markdown. Next file");
          next;
        }
      }

      debug(2, "Process $filename to $html_file");
      publish($filename, $html_file);
    }
  }
}


sub publish() {
  my ($source, $dest) = @_;

  # Get markdown.
  my ($title, $markdown) = get_markdown($source);

  # Get html content.
  my $html = convert_to_html($title, $markdown);

  print("Publish: $dest\n");

  open(my $fh, ">", $dest) or die "Error: Open $dest failed: $!";
  print $fh $html;
  close($fh);
}


sub get_markdown() {
  my $source = shift;
  # Get markdown content.
  open(my $fh, "<", $source) or die "Error: $!";
  # The first line is the title.
  my $title = <$fh>;
  # The rest is markdown.
  my $markdown = do { local $/; <$fh> };
  close($fh);
  # Add the title back to markdown.
  $markdown = $title . $markdown;
  chomp($title);

  return ($title, $markdown);
}


sub convert_to_html() {
  my ($title, $markdown) = @_;
  # Convert markdown to html.
  my $converter = Markdown::Perl->new();
  $converter->set_mode("cmark");
  my $content = $converter->convert($markdown);
  my $html = <<EOL
<!DOCTYPE html>
<html lang="en">
<!-- DO NOT EDIT. This file is automatically generated. -->
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<style>
body {
  width: auto;
  max-width: 1024px;
  padding: 0 8px;
}
code {
  background-color: #f6f8fa;
  color: #24292f;
  font-family: monospace;
  overflow-x: auto;
  white-space: pre;
}
pre {
  background-color: #f6f8fa;
  color: #24292f;
  padding: 8px;
  border-radius: 4px;
  padding: 0 4px;
  border: 1px solid #333333;
}
pre code {
  display: block;
  font-family: monospace;
  font-size: 85%;
  padding: 8px;
  line-height: 1.5;
  overflow-x: auto;
  white-space: pre;
}
</style>
<title>$title</title>
</head>
<body>
$content
</body>
</html>
EOL
;
  return $html
}


main()
